#!/usr/bin/env bash
# Bootstrap mailcow.conf for Coolify (non-interactive). Safe to run on every deploy.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

coolify_persistent_root() {
  if [ -n "${COOLIFY_RESOURCE_UUID:-}" ] && [ -d "/data/coolify/applications/${COOLIFY_RESOURCE_UUID}" ]; then
    echo "/data/coolify/applications/${COOLIFY_RESOURCE_UUID}"
  fi
}

# Coolify bind-mounts use the persistent app dir, not only /artifacts during build.
PERSIST_ROOT="$(coolify_persistent_root || true)"
WORK_ROOT="${PERSIST_ROOT:-$ROOT}"
cd "$WORK_ROOT"

MAILCOW_HOSTNAME="${MAILCOW_HOSTNAME:-mail.sowtech.io}"
MAILCOW_TZ="${TZ:-${MAILCOW_TZ:-America/Sao_Paulo}}"
SKIP_CLAMD="${SKIP_CLAMD:-y}"
ENABLE_IPV6="${ENABLE_IPV6:-true}"
DOCKER_COMPOSE_VERSION="${DOCKER_COMPOSE_VERSION:-native}"
COMPOSE_PROJECT_NAME="${COMPOSE_PROJECT_NAME:-mailcowdockerized}"

random_alnum() {
  local len="${1:-28}"
  # head closes the pipe early; with pipefail that yields exit 141 (SIGPIPE).
  (
    set +o pipefail
    LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom 2>/dev/null | head -c "$len"
  )
}

ensure_placeholder_files() {
  mkdir -p data/assets/ssl data/assets/ssl-example data/conf/rspamd/override.d
  [ ! -f ./data/conf/rspamd/override.d/worker-controller-password.inc ] && \
    echo '# Placeholder' > ./data/conf/rspamd/override.d/worker-controller-password.inc
}

# SOGo bind-mounts expect files; if missing, Docker creates directories and the stack fails.
ensure_sogo_custom_assets_in() {
  local base="$1"
  local defaults="${ROOT}/deploy/sogo-defaults"
  local names=(custom-shortlogo.svg custom-fulllogo.svg custom-fulllogo.png)
  [ -d "$base" ] || return 0
  mkdir -p "${base}/data/conf/sogo"
  for name in "${names[@]}"; do
    local dest="${base}/data/conf/sogo/${name}"
    if [ -d "$dest" ]; then
      echo "Removing mistaken directory ${dest} (SOGo needs a file mount)..."
      rm -rf "$dest"
    fi
    if [ ! -f "$dest" ] && [ -f "${defaults}/${name}" ]; then
      cp "${defaults}/${name}" "$dest"
      echo "Installed SOGo asset ${dest}"
    fi
  done
}

ensure_sogo_custom_assets() {
  ensure_sogo_custom_assets_in "$WORK_ROOT"
  if [ "$ROOT" != "$WORK_ROOT" ]; then
    ensure_sogo_custom_assets_in "$ROOT"
  fi
}

ensure_snake_oil_certs() {
  if [ ! -f data/assets/ssl/cert.pem ] || [ ! -f data/assets/ssl/key.pem ]; then
    echo "Generating initial snake-oil TLS material for ${MAILCOW_HOSTNAME}..."
    openssl req -x509 -newkey rsa:4096 \
      -keyout data/assets/ssl-example/key.pem \
      -out data/assets/ssl-example/cert.pem \
      -days 365 \
      -subj "/C=BR/O=Sowtech/CN=${MAILCOW_HOSTNAME}" \
      -sha256 -nodes 2>/dev/null
    cp -n data/assets/ssl-example/*.pem data/assets/ssl/ 2>/dev/null || \
      cp data/assets/ssl-example/*.pem data/assets/ssl/
  fi
}

write_mailcow_conf() {
  local dbpass dbroot redispass sogo_key
  dbpass="${DBPASS:-$(random_alnum 28)}"
  dbroot="${DBROOT:-$(random_alnum 28)}"
  redispass="${REDISPASS:-$(random_alnum 28)}"
  sogo_key="${SOGO_URL_ENCRYPTION_KEY:-$(random_alnum 16)}"

  cat > mailcow.conf <<EOF
# Generated by deploy/coolify-ensure-config.sh — do not commit (see mailcow.conf.example).
MAILCOW_HOSTNAME=${MAILCOW_HOSTNAME}
MAILCOW_PASS_SCHEME=BLF-CRYPT

DBNAME=mailcow
DBUSER=mailcow
DBPASS=${dbpass}
DBROOT=${dbroot}

REDISPASS=${redispass}

HTTP_PORT=${HTTP_PORT:-80}
HTTP_BIND=${HTTP_BIND:-}
HTTPS_PORT=${HTTPS_PORT:-443}
HTTPS_BIND=${HTTPS_BIND:-}
HTTP_REDIRECT=${HTTP_REDIRECT:-y}

SMTP_PORT=${SMTP_PORT:-25}
SMTPS_PORT=${SMTPS_PORT:-465}
SUBMISSION_PORT=${SUBMISSION_PORT:-587}
IMAP_PORT=${IMAP_PORT:-143}
IMAPS_PORT=${IMAPS_PORT:-993}
POP_PORT=${POP_PORT:-110}
POPS_PORT=${POPS_PORT:-995}
SIEVE_PORT=${SIEVE_PORT:-4190}
DOVEADM_PORT=127.0.0.1:19991
SQL_PORT=127.0.0.1:13306
REDIS_PORT=127.0.0.1:7654

TZ=${MAILCOW_TZ}
COMPOSE_PROJECT_NAME=${COMPOSE_PROJECT_NAME}
DOCKER_COMPOSE_VERSION=${DOCKER_COMPOSE_VERSION}

ACL_ANYONE=disallow
MAILDIR_GC_TIME=7200
ADDITIONAL_SAN=
AUTODISCOVER_SAN=y
ADDITIONAL_SERVER_NAMES=

SKIP_LETS_ENCRYPT=${SKIP_LETS_ENCRYPT:-n}
ACME_DNS_CHALLENGE=n
ACME_DNS_PROVIDER=dns_xxx
ACME_ACCOUNT_EMAIL=me@example.com
ENABLE_SSL_SNI=n
SKIP_IP_CHECK=n
SKIP_HTTP_VERIFICATION=n
SKIP_UNBOUND_HEALTHCHECK=n
SKIP_CLAMD=${SKIP_CLAMD}
SKIP_OLEFY=n
SKIP_SOGO=n
SKIP_FTS=n
FTS_HEAP=128
FTS_PROCS=1
ALLOW_ADMIN_EMAIL_LOGIN=n
USE_WATCHDOG=y
WATCHDOG_NOTIFY_BAN=n
WATCHDOG_NOTIFY_START=y
WATCHDOG_EXTERNAL_CHECKS=n
WATCHDOG_VERBOSE=n
LOG_LINES=9999

IPV4_NETWORK=${IPV4_NETWORK:-172.22.1}
IPV6_NETWORK=fd4d:6169:6c63:6f77::/64

MAILDIR_SUB=Maildir
SOGO_EXPIRE_SESSION=480
SOGO_URL_ENCRYPTION_KEY=${sogo_key}

DOVECOT_MASTER_USER=
DOVECOT_MASTER_PASS=
WEBAUTHN_ONLY_TRUSTED_VENDORS=n
SPAMHAUS_DQS_KEY=
ENABLE_IPV6=${ENABLE_IPV6}
DISABLE_NETFILTER_ISOLATION_RULE=n
EOF
  chmod 600 mailcow.conf
}

write_app_info() {
  if [ ! -f data/web/inc/app_info.inc.php ]; then
    cat > data/web/inc/app_info.inc.php <<'PHP'
<?php
  $MAILCOW_GIT_VERSION="coolify-deploy";
  $MAILCOW_LAST_GIT_VERSION="";
  $MAILCOW_GIT_OWNER="Chebl20";
  $MAILCOW_GIT_REPO="mailcow-dockerized";
  $MAILCOW_GIT_URL="https://github.com/Chebl20/mailcow-dockerized";
  $MAILCOW_GIT_COMMIT="";
  $MAILCOW_GIT_COMMIT_DATE="";
  $MAILCOW_BRANCH="master";
  $MAILCOW_UPDATEDAT=0;
?>
PHP
  fi
}

# Coolify may write its own .env; mailcow expects variables in mailcow.conf.
# Compose is always invoked with --env-file mailcow.conf (see deploy/COOLIFY.md).
if [ -f mailcow.conf ]; then
  echo "mailcow.conf already exists — keeping secrets and DB credentials."
else
  if [ -f mailcow.conf.example ] && [ "${COOLIFY_USE_EXAMPLE_CONF:-n}" = "y" ]; then
    cp mailcow.conf.example mailcow.conf
    chmod 600 mailcow.conf
    echo "Created mailcow.conf from mailcow.conf.example (COOLIFY_USE_EXAMPLE_CONF=y)."
  else
    echo "Creating new mailcow.conf for ${MAILCOW_HOSTNAME}..."
    write_mailcow_conf
  fi
fi

ensure_placeholder_files
ensure_sogo_custom_assets
ensure_snake_oil_certs
write_app_info

# Coolify default compose uses .env in artifacts — mirror mailcow.conf when present.
if [ -f mailcow.conf ]; then
  cp -f mailcow.conf "${ROOT}/.env"
  cp -f mailcow.conf .env 2>/dev/null || true
fi

# Optional: apply non-secret overrides from Coolify env on every deploy
if [ -f mailcow.conf ] && [ "${COOLIFY_SYNC_HOSTNAME:-y}" = "y" ] && [ -n "${MAILCOW_HOSTNAME}" ]; then
  sed -i "s/^MAILCOW_HOSTNAME=.*/MAILCOW_HOSTNAME=${MAILCOW_HOSTNAME}/" mailcow.conf
  sed -i "s/^TZ=.*/TZ=${MAILCOW_TZ}/" mailcow.conf
fi

echo "mailcow.conf ready ($(wc -l < mailcow.conf) lines)."
